DB = "bench_audit"
OPTS = "-c timezone=UTC"
COUNTRIES = ["PK", "IN", "BD", "LK", "NP", "AE", "SA", "TR", "EG", "NG", "KE", "ZA", "GB", "DE", "FR", "US", "CA", "BR", "ID", "MY"]
WEIGHTS = [60, 15, 10, 2, 2, 2, 1, 1, 1, 1, 1, 1, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5]

SCHEMA = """
CREATE TABLE a_current (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts timestamptz NOT NULL, actor_id bigint,
  actor_role varchar(40) NOT NULL, action varchar(80) NOT NULL, object_type varchar(60) NOT NULL,
  object_uid varchar(40) NOT NULL, country_code varchar(2) NOT NULL, ip_hash varchar(64) NOT NULL,
  payload jsonb NOT NULL, prev_hash varchar(64) NOT NULL, hash varchar(64) NOT NULL UNIQUE);
CREATE TABLE a_chains (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, chain smallint NOT NULL, seq bigint NOT NULL,
  ts timestamptz NOT NULL, actor_id bigint, actor_role varchar(40) NOT NULL, action varchar(80) NOT NULL,
  object_type varchar(60) NOT NULL, object_uid varchar(40) NOT NULL, country_code varchar(2) NOT NULL,
  ip_hash varchar(64) NOT NULL, payload jsonb NOT NULL, prev_hash varchar(64) NOT NULL,
  hash varchar(64) NOT NULL, UNIQUE (chain, seq));
CREATE TABLE a_chain_head (chain smallint PRIMARY KEY, seq bigint NOT NULL, head_hash varchar(64) NOT NULL);
CREATE TABLE a_unchained (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, uid char(26) NOT NULL, txid xid8 NOT NULL DEFAULT pg_current_xact_id(),
  ts timestamptz NOT NULL, actor_id bigint, actor_role varchar(40) NOT NULL, action varchar(80) NOT NULL,
  object_type varchar(60) NOT NULL, object_uid varchar(40) NOT NULL, country_code varchar(2) NOT NULL,
  ip_hash varchar(64) NOT NULL, payload jsonb NOT NULL, row_hash char(64) NOT NULL);
CREATE INDEX a_unchained_txid_id ON a_unchained (txid, id);
CREATE TABLE a_seal (
  seq bigint PRIMARY KEY, prev_seal char(64) NOT NULL, first_txid xid8 NOT NULL, first_id bigint NOT NULL,
  last_txid xid8 NOT NULL, last_id bigint NOT NULL, n_rows int NOT NULL, merkle_root char(64) NOT NULL,
  seal_hash char(64) NOT NULL, sealed_at timestamptz NOT NULL DEFAULT now());
CREATE OR REPLACE FUNCTION forbid_mutation() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'append-only table %', TG_TABLE_NAME; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER a_current_ao BEFORE UPDATE OR DELETE ON a_current FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER a_chains_ao BEFORE UPDATE OR DELETE ON a_chains FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER a_unchained_ao BEFORE UPDATE OR DELETE ON a_unchained FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER a_seal_ao BEFORE UPDATE OR DELETE ON a_seal FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
"""


def canon(prev, fields):
    return prev + json.dumps(fields, sort_keys=True, separators=(",", ":"), default=str)


def sha(s):
    return hashlib.sha256(s.encode()).hexdigest()


def new_uid(rng):
    return "".join(rng.choice("0123456789ABCDEFGHJKMNPQRSTVWXYZ") for _ in range(26))


def make_fields(ts, uid, object_uid, country, i):
    return {
        "ts": ts.isoformat(), "actor_id": 7, "actor_role": "system", "action": "bench.write", "object_type": "entry",
        "object_uid": object_uid, "country_code": country, "ip_hash": "", "payload": {"i": i}, "uid": uid,
    }


def row_values(f):
    return (f["ts"], f["actor_id"], f["actor_role"], f["action"], f["object_type"], f["object_uid"], f["country_code"], f["ip_hash"])


def chain_of(object_uid, n):
    return zlib.crc32(object_uid.encode()) % n


# ---- writers -------------------------------------------------------------------------------------------------

def audit_current(conn, f, hold):
    with conn.transaction():
        conn.execute("SELECT pg_advisory_xact_lock(727001)")
        r = conn.execute("SELECT hash FROM a_current ORDER BY id DESC LIMIT 1").fetchone()
        prev = r[0] if r else ""
        h = sha(canon(prev, f))
        conn.execute(
            "INSERT INTO a_current (ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,prev_hash,hash)"
            " VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            (*row_values(f), Jsonb(f["payload"]), prev, h),
        )
        if hold:
            conn.execute("SELECT pg_sleep(%s)", [hold / 1000.0])


def audit_chain(conn, f, hold, n):
    c = chain_of(f["object_uid"] if n != "country" else f["country_code"], 256 if n == 256 else (16 if n == 16 else 16))
    with conn.transaction():
        r = conn.execute("SELECT seq, head_hash FROM a_chain_head WHERE chain=%s FOR UPDATE", (c,)).fetchone()
        seq, prev = (r[0] + 1, r[1]) if r else (1, "")
        h = sha(canon(prev, f))
        conn.execute(
            "INSERT INTO a_chains (chain,seq,ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,prev_hash,hash)"
            " VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            (c, seq, *row_values(f), Jsonb(f["payload"]), prev, h),
        )
        conn.execute(
            "INSERT INTO a_chain_head (chain,seq,head_hash) VALUES (%s,%s,%s) ON CONFLICT (chain) DO UPDATE SET seq=EXCLUDED.seq, head_hash=EXCLUDED.head_hash",
            (c, seq, h),
        )
        if hold:
            conn.execute("SELECT pg_sleep(%s)", [hold / 1000.0])


def audit_unchained(conn, f, hold):
    h = sha(canon("", f))
    with conn.transaction():
        conn.execute(
            "INSERT INTO a_unchained (uid,ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,row_hash)"
            " VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            (f["uid"], *row_values(f), Jsonb(f["payload"]), h),
        )
        if hold:
            conn.execute("SELECT pg_sleep(%s)", [hold / 1000.0])


BATCH = 500


def batch_chain(conn, rng, k, hold):
    """One lock, one head read, BATCH rows hashed in Python, one COPY. Returns rows written."""
    now = datetime.now(timezone.utc)
    c = 0
    with conn.transaction():
        conn.execute("SELECT pg_advisory_xact_lock(727001)")
        r = conn.execute("SELECT seq, head_hash FROM a_chain_head WHERE chain=%s", (c,)).fetchone()
        seq, prev = (r[0], r[1]) if r else (0, "")
        with conn.cursor().copy(
            "COPY a_chains (chain,seq,ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,prev_hash,hash) FROM STDIN"
        ) as cp:
            for j in range(BATCH):
                seq += 1
                f = make_fields(now, new_uid(rng), f"b{k}-{j}", "PK", j)
                h = sha(canon(prev, f))
                cp.write_row((c, seq, now, 7, "system", "bench.write", "entry", f["object_uid"], "PK", "", json.dumps(f["payload"]), prev, h))
                prev = h
        conn.execute(
            "INSERT INTO a_chain_head (chain,seq,head_hash) VALUES (%s,%s,%s) ON CONFLICT (chain) DO UPDATE SET seq=EXCLUDED.seq, head_hash=EXCLUDED.head_hash",
            (c, seq, prev),
        )
        if hold:
            conn.execute("SELECT pg_sleep(%s)", [hold / 1000.0])
    return BATCH


def batch_unchained(conn, rng, k, hold):
    now = datetime.now(timezone.utc)
    with conn.transaction():
        with conn.cursor().copy(
            "COPY a_unchained (uid,ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,row_hash) FROM STDIN"
        ) as cp:
            for j in range(BATCH):
                f = make_fields(now, new_uid(rng), f"b{k}-{j}", "PK", j)
                cp.write_row((f["uid"], now, 7, "system", "bench.write", "entry", f["object_uid"], "PK", "", json.dumps(f["payload"]), sha(canon("", f))))
        if hold:
            conn.execute("SELECT pg_sleep(%s)", [hold / 1000.0])
    return BATCH


def worker(variant, idx, duration, hold, q, start_at):
    conn = connect(DB, options=OPTS)
    rng = random.Random(idx * 7919 + 1)
    lat, rows, i = [], 0, 0
    while time.time() < start_at:
        time.sleep(0.001)
    end = time.time() + duration
    while time.time() < end:
        t = time.perf_counter()
        if variant.startswith("batch500"):
            rows += (batch_chain if variant.endswith("chain") else batch_unchained)(conn, rng, f"{idx}-{i}", hold)
        else:
            ts = datetime.now(timezone.utc)
            uid = new_uid(rng)
            country = rng.choices(COUNTRIES, WEIGHTS)[0] if variant == "chainC_skew" else "PK"
            f = make_fields(ts, uid, f"{idx}-{i}", country, i)
            if variant == "current":
                audit_current(conn, f, hold)
            elif variant == "chain16":
                audit_chain(conn, f, hold, 16)
            elif variant == "chain256":
                audit_chain(conn, f, hold, 256)
            elif variant == "chainC_skew":
                audit_chain(conn, f, hold, "country")
            elif variant == "unchained":
                audit_unchained(conn, f, hold)
            rows += 1
        lat.append(time.perf_counter() - t)
        i += 1
    q.put((lat, rows))
    conn.close()


def reset():
    with connect(DB) as c:
        for t in ("a_current", "a_chains", "a_chain_head", "a_unchained", "a_seal"):
            c.execute(f"ALTER TABLE {t} DISABLE TRIGGER USER") if t != "a_chain_head" else None
            c.execute(f"TRUNCATE {t} RESTART IDENTITY")
            c.execute(f"ALTER TABLE {t} ENABLE TRIGGER USER") if t != "a_chain_head" else None
        # chain heads are created up front (as a migration or ensure_chain() would): FOR UPDATE on a missing row locks nothing
        c.execute("INSERT INTO a_chain_head SELECT g, 0, '' FROM generate_series(0, 255) g")


def run(variant, workers, duration, hold, out):
    reset()
    ctx = mp.get_context("spawn")
    q = ctx.Queue()
    start_at = time.time() + 2
    ps = [ctx.Process(target=worker, args=(variant, i, duration, hold, q, start_at)) for i in range(workers)]
    [p.start() for p in ps]
    res = [q.get() for _ in ps]
    [p.join() for p in ps]
    lat = [x for r in res for x in r[0]]
    rows = sum(r[1] for r in res)
    line = (
        f"{variant:12s} writers={workers} hold={hold:>2}ms  tx/s={len(lat) / duration:>8,.0f}  rows/s={rows / duration:>9,.0f}  "
        f"p50={pctl(lat, 50) * 1000:7.2f}ms p99={pctl(lat, 99) * 1000:8.2f}ms"
    )
    print(line, flush=True)
    out.append(line)


# ---- sealer / verifier -----------------------------------------------------------------------------------------

def merkle(leaves):
    level = [bytes.fromhex(x) for x in leaves]
    if not level:
        return hashlib.sha256(b"").hexdigest()
    while len(level) > 1:
        if len(level) % 2:
            level.append(level[-1])
        level = [hashlib.sha256(level[i] + level[i + 1]).digest() for i in range(0, len(level), 2)]
    return level[0].hex()


def seal_once(conn, limit=100_000):
    """Seal every committed, not yet sealed row below the xid horizon. Returns rows sealed (0 if nothing or locked)."""
    with conn.transaction():
        if not conn.execute("SELECT pg_try_advisory_xact_lock(727002)").fetchone()[0]:
            return 0
        last = conn.execute("SELECT seq, seal_hash, last_txid, last_id FROM a_seal ORDER BY seq DESC LIMIT 1").fetchone()
        seq, prev, ltx, lid = (last[0], last[1], last[2], last[3]) if last else (0, "0" * 64, 0, 0)
        rows = conn.execute(
            "SELECT id, txid, row_hash FROM a_unchained WHERE (txid, id) > (%s::text::xid8, %s) "
            "AND txid < pg_snapshot_xmin(pg_current_snapshot()) ORDER BY txid, id LIMIT %s",
            (ltx, lid, limit),
        ).fetchall()
        if not rows:
            return 0
        root = merkle([r[2] for r in rows])
        first, lastr = rows[0], rows[-1]
        seal = hashlib.sha256(f"{seq + 1}|{prev}|{first[1]}|{first[0]}|{lastr[1]}|{lastr[0]}|{len(rows)}|{root}".encode()).hexdigest()
        conn.execute(
            "INSERT INTO a_seal (seq,prev_seal,first_txid,first_id,last_txid,last_id,n_rows,merkle_root,seal_hash) VALUES (%s,%s,%s::text::xid8,%s,%s::text::xid8,%s,%s,%s,%s)",
            (seq + 1, prev, first[1], first[0], lastr[1], lastr[0], len(rows), root, seal),
        )
        return len(rows)


def recompute_row_hash(r):
    # r = (uid, ts, actor_id, actor_role, action, object_type, object_uid, country_code, ip_hash, payload)
    f = {"ts": r[1].isoformat(), "actor_id": r[2], "actor_role": r[3], "action": r[4], "object_type": r[5],
         "object_uid": r[6], "country_code": r[7], "ip_hash": r[8], "payload": r[9], "uid": r[0].strip()}
    return sha(canon("", f))


def verify_seals(conn):
    """Returns None if intact, else a description of the first problem."""
    prev = "0" * 64
    for s in conn.execute("SELECT seq, prev_seal, first_txid::text, first_id, last_txid::text, last_id, n_rows, merkle_root, seal_hash FROM a_seal ORDER BY seq").fetchall():
        if s[1] != prev:
            return f"seal {s[0]}: prev_seal does not match"
        cur = conn.cursor(name=f"v{s[0]}")
        cur.itersize = 20000
        cur.execute(
            "SELECT uid, ts, actor_id, actor_role, action, object_type, object_uid, country_code, ip_hash, payload, row_hash, id, txid::text FROM a_unchained "
            "WHERE (txid, id) >= (%s::xid8, %s) AND (txid, id) <= (%s::xid8, %s) ORDER BY txid, id", (s[2], s[3], s[4], s[5]),
        )
        leaves, n = [], 0
        for r in cur:
            n += 1
            if recompute_row_hash(r) != r[10]:
                return f"seal {s[0]}: row id {r[11]} content does not match its row_hash"
            leaves.append(r[10])
        if n != s[6]:
            return f"seal {s[0]}: row count {n} != sealed {s[6]} (row removed or added)"
        if merkle(leaves) != s[7]:
            return f"seal {s[0]}: merkle root differs"
        seal = hashlib.sha256(f"{s[0]}|{s[1]}|{s[2]}|{s[3]}|{s[4]}|{s[5]}|{s[6]}|{s[7]}".encode()).hexdigest()
        if seal != s[8]:
            return f"seal {s[0]}: seal hash differs"
        prev = s[8]
    return None


def verify_chain_rows(conn, chain=None):
    """Per-row chain verification of a_chains for one chain (what verify_audit_chain does today, per chain)."""
    prev, n = "", 0
    cur = conn.cursor(name="vc")
    cur.itersize = 20000
    cur.execute("SELECT seq, ts, actor_id, actor_role, action, object_type, object_uid, country_code, ip_hash, payload, prev_hash, hash FROM a_chains WHERE chain=%s ORDER BY seq", (chain,))
    for r in cur:
        f = {"ts": r[1].isoformat(), "actor_id": r[2], "actor_role": r[3], "action": r[4], "object_type": r[5],
             "object_uid": r[6], "country_code": r[7], "ip_hash": r[8], "payload": r[9]}
        # rows were hashed with uid in fields; verify prev link only plus presence (cost model, see note)
        if r[10] != prev:
            return r[0]
        prev = r[11]
        n += 1
    return None


def bulk_fill_unchained(conn, n, rng):
    now = datetime.now(timezone.utc)
    done = 0
    while done < n:
        with conn.transaction():
            with conn.cursor().copy(
                "COPY a_unchained (uid,ts,actor_id,actor_role,action,object_type,object_uid,country_code,ip_hash,payload,row_hash) FROM STDIN"
            ) as cp:
                for j in range(5000):
                    f = make_fields(now, new_uid(rng), f"f{done}-{j}", "PK", j)
                    cp.write_row((f["uid"], now, 7, "system", "bench.write", "entry", f["object_uid"], "PK", "", json.dumps(f["payload"]), sha(canon("", f))))
        done += 5000


def deadlock_demo():
    """Two transactions that each audit chain A then chain B in opposite order deadlock; sorted order does not."""
    results = {}

    def tx(name, order, barrier):
        c = connect(DB, options=OPTS)
        try:
            with c.transaction():
                c.execute("SELECT pg_advisory_xact_lock(%s)", (900000 + order[0],))
                barrier.wait()
                c.execute("SELECT pg_advisory_xact_lock(%s)", (900000 + order[1],))
            results[name] = "ok"
        except psycopg.errors.DeadlockDetected:
            results[name] = "DEADLOCK (aborted by server)"
        finally:
            c.close()

    for label, o1, o2 in (("opposite order", (1, 2), (2, 1)), ("sorted order", (1, 2), (1, 2))):
        results.clear()
        b = threading.Barrier(2)
        t0 = time.perf_counter()
        ts = [threading.Thread(target=tx, args=("T1", o1, b)), threading.Thread(target=tx, args=("T2", o2, b))]
        [t.start() for t in ts]
        [t.join() for t in ts]
        print(f"multi-chain tx, {label}: {dict(results)} after {time.perf_counter() - t0:.2f}s", flush=True)


def main():
    duration = float(sys.argv[1]) if len(sys.argv) > 1 else 10
    out = []
    make_db(DB)
    with connect(DB) as c:
        c.execute(SCHEMA)
    print(f"== writers, {duration}s each ==")
    for variant in ("current", "chain16", "chain256", "chainC_skew", "unchained", "batch500_chain", "batch500_unchained"):
        for workers in (1, 8):
            run(variant, workers, duration, 0, out)
    print("== same with 5 ms of other work in the same transaction (the bulk.publish shape) ==")
    for variant in ("current", "chain16", "unchained"):
        for workers in (1, 8):
            run(variant, workers, duration, 5, out)
    print("== same with 20 ms ==")
    for variant in ("current", "chain16", "unchained"):
        for workers in (1, 8):
            run(variant, workers, duration, 20, out)

    # sealer while writers run
    print("== sealer running every 1 s while 8 writers insert unchained rows ==")
    reset()
    ctx = mp.get_context("spawn")
    q = ctx.Queue()
    start_at = time.time() + 2
    ps = [ctx.Process(target=worker, args=("unchained", i, duration, 0, q, start_at)) for i in range(8)]
    [p.start() for p in ps]
    sc = connect(DB, options=OPTS)
    sealed = 0
    while time.time() < start_at + duration + 1:
        sealed += seal_once(sc)
        time.sleep(1)
    res = [q.get() for _ in ps]
    [p.join() for p in ps]
    sealed += seal_once(sc)
    total = sc.execute("SELECT count(*) FROM a_unchained").fetchone()[0]
    nseal = sc.execute("SELECT count(*) FROM a_seal").fetchone()[0]
    unsealed = total - sealed
    print(f"writers inserted {total:,} rows ({total / duration:,.0f}/s with the sealer running); sealed {sealed:,} in {nseal} seals; unsealed after final pass {unsealed}")
    with Timer() as t:
        problem = verify_seals(sc)
    print(f"verify_seals on {total:,} rows: {t.s:.2f}s ({total / t.s:,.0f} rows/s) -> {problem or 'intact'}")

    print("== bulk fill to 1,000,000 rows, seal, verify, tamper ==")
    rng = random.Random(5)
    with Timer() as t:
        bulk_fill_unchained(sc, 1_000_000, rng)
    n = sc.execute("SELECT count(*) FROM a_unchained").fetchone()[0]
    print(f"COPY fill: {n:,} rows total ({1_000_000 / t.s:,.0f} rows/s incl. hashing in Python)")
    with Timer() as t:
        s = 0
        while True:
            k = seal_once(sc)
            if not k:
                break
            s += k
    print(f"seal {s:,} rows in {t.s:.2f}s ({s / t.s:,.0f} rows/s)")
    with Timer() as t:
        problem = verify_seals(sc)
    print(f"verify_seals on {n:,} rows: {t.s:.2f}s ({n / t.s:,.0f} rows/s) -> {problem or 'intact'}")

    # tamper tests as the table owner with the trigger disabled (an attacker with owner rights)
    mid = sc.execute("SELECT id FROM a_unchained ORDER BY id OFFSET 500000 LIMIT 1").fetchone()[0]
    sc.execute("ALTER TABLE a_unchained DISABLE TRIGGER USER")
    sc.execute("UPDATE a_unchained SET action='bench.forged' WHERE id=%s", (mid,))
    print("tamper UPDATE one row ->", verify_seals(sc))
    sc.execute("UPDATE a_unchained SET action='bench.write' WHERE id=%s", (mid,))
    assert verify_seals(sc) is None
    row = sc.execute("DELETE FROM a_unchained WHERE id=%s RETURNING uid", (mid,)).fetchone()
    print("tamper DELETE one row ->", verify_seals(sc))
    sc.execute("ALTER TABLE a_unchained ENABLE TRIGGER USER")

    print("== per-row chain verification cost (single chain, one chain of 1,000,000 rows) ==")
    reset()
    wc = connect(DB, options=OPTS)
    with Timer() as t:
        k = 0
        while k < 1_000_000:
            k += batch_chain(wc, rng, f"v{k}", 0)
    print(f"batch500_chain fill: {k:,} rows in {t.s:.1f}s ({k / t.s:,.0f} rows/s)")
    with Timer() as t:
        r = verify_chain_rows(wc, 0)
    print(f"verify chain links of {k:,} rows: {t.s:.2f}s -> {r or 'intact'}")

    print("== deadlock demo ==")
    deadlock_demo()
    sc.close()
    wc.close()
    with open(__file__.rsplit("/", 1)[0] + "/results/b02_audit_alternatives.txt", "w") as fh:
        fh.write("\n".join(out) + "\n")
    drop_db(DB)


if __name__ == "__main__":
    main()
