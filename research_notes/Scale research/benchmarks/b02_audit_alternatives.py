"""B02: audit write path alternatives, raw psycopg, scratch database bench_audit.

Variants (all write the same row shape as core_auditlog; 1 and 8 writer processes; optional hold inside the tx):
  current      replica of today's audit(): advisory lock 727001, SELECT last hash, INSERT, COMMIT (single global chain)
  chain16      16 chains, chain chosen by crc32(object_uid) % 16; lock per chain; head row per chain (SELECT .. FOR UPDATE)
  chain256     same, 256 chains
  chainC_skew  chain by country (20 countries, 60% PK / 15% IN / 10% BD): shows skew limit
  unchained    no lock: insert row with its own row hash (sha256 of canonical row, includes uid) and txid; sealed later
  batch500_*   bulk path: 500 rows per transaction (single chain: one lock, one head read, COPY; unchained: COPY)

Then the sealer (Merkle seal chain over unchained rows, horizon = pg_snapshot_xmin), verifier, tamper tests, anchor check
and a deadlock demonstration for multi-chain transactions.

Run: .venv/bin/python "research_notes/Scale research/benchmarks/b02_audit_alternatives.py" [seconds]
"""

